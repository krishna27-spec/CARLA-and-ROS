"""Generate worlds/cone_track.world and config/cone_track_path.csv.

A closed, counter-clockwise circuit marked by traffic cones: a bottom chicane,
a wide right-hand end, a top straight with a U-shaped notch (hairpin), a
sweeper and an S-bend on the left. The centre line is a periodic cubic spline
through WAYPOINTS; cones stand HALF_WIDTH either side of it every CONE_SPACING m.
Run from sim_pkg/ with a python that has numpy + scipy (python3 -s):
    python3 -s tools/make_cone_track.py
"""
import math
import os

import numpy as np
from scipy.interpolate import CubicSpline

HALF_WIDTH = 0.75      # centre line to cone line [m]
CONE_SPACING = 0.9     # along each side [m]
WAYPOINTS = [
    (-4.6, -3.5), (-2.5, -3.3), (-0.5, -2.6), (1.5, -3.5), (3.8, -3.3),
    (6.0, -2.4), (7.0, -0.4), (6.5, 1.6), (5.2, 3.1),            # right end
    (4.2, 3.5), (3.4, 3.1), (3.15, 2.3), (3.1, 0.4),             # into the notch
    (2.75, -0.45), (1.9, -0.8), (1.05, -0.45), (0.7, 0.4),       # hairpin
    (0.6, 2.4), (-0.6, 3.5), (-2.6, 3.4), (-4.4, 2.6),
    (-5.9, 1.2), (-5.7, -0.3), (-6.3, -1.6), (-6.0, -2.8),       # left S-bend
]
OUT = os.path.join(os.path.dirname(__file__), '..')


def centre_line(spacing=0.02):
    w = np.array(WAYPOINTS + [WAYPOINTS[0]], dtype=float)
    s = np.concatenate(([0.0], np.cumsum(np.hypot(*np.diff(w, axis=0).T))))
    cs = CubicSpline(s, w, bc_type='periodic')
    t = np.arange(0.0, s[-1], spacing)
    p, d = cs(t), cs(t, 1)
    yaw = np.arctan2(d[:, 1], d[:, 0])
    return t, p, yaw


def analyse(t, p, yaw):
    dyaw = np.diff(np.unwrap(np.append(yaw, yaw[0])))
    ds = np.hypot(*np.diff(np.vstack((p, p[:1])), axis=0).T)
    arc = np.concatenate(([0.0], np.cumsum(ds)))[:-1]
    curv = np.abs(dyaw / ds)
    sub = p[::10]; ts = arc[::10]; total = arc[-1] + ds[-1]
    d = np.hypot(sub[:, None, 0] - sub[None, :, 0], sub[:, None, 1] - sub[None, :, 1])
    far = np.abs(ts[:, None] - ts[None, :]); far = np.minimum(far, total - far) > 3.0
    return dict(length=total, min_radius=1 / curv.max(),
                min_separation=np.where(far, d, 99).min(),
                xlim=(p[:, 0].min(), p[:, 0].max()), ylim=(p[:, 1].min(), p[:, 1].max()))


def cone_positions(t, p, yaw):
    cones = []
    for sgn in (+1, -1):
        edge = p + sgn * HALF_WIDTH * np.column_stack((-np.sin(yaw), np.cos(yaw)))
        seg = np.hypot(*np.diff(np.vstack((edge, edge[:1])), axis=0).T)
        arc = np.concatenate(([0.0], np.cumsum(seg)))
        n = int(arc[-1] // CONE_SPACING)
        for k in range(n):
            i = np.searchsorted(arc, k * arc[-1] / n)
            cones.append((edge[i, 0], edge[i, 1], sgn))
    return cones


def main():
    t, p, yaw = centre_line()
    info = analyse(t, p, yaw)
    cones = cone_positions(t, p, yaw)
    inc = '\n'.join(
        f'    <include><name>cone_{i}</name><uri>model://traffic_cone</uri>'
        f'<pose>{x:.3f} {y:.3f} 0 0 0 0</pose></include>'
        for i, (x, y, _) in enumerate(cones))
    sx, sy = p[0]
    world = f'''<?xml version="1.0"?>
<!-- GENERATED by tools/make_cone_track.py - edit the script, not this file.
     Cone circuit, counter-clockwise. Spawn the car at x={sx:.1f} y={sy:.1f} yaw={yaw[0]:.3f}.
     Needs sim_pkg/models on GAZEBO_MODEL_PATH (car.launch.py sets it). -->
<sdf version="1.6">
  <world name="cone_track">
    <include><uri>model://ground_plane</uri></include>
    <include><uri>model://sun</uri></include>
{inc}
    <model name="start_line">
      <static>true</static>
      <pose>{sx:.3f} {sy:.3f} 0.003 0 0 {yaw[0]:.4f}</pose>
      <link name="link">
        <visual name="v"><geometry><box><size>0.08 {2 * HALF_WIDTH:.2f} 0.004</size></box></geometry>
          <material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse></material></visual>
      </link>
    </model>
    <gui><camera name="user_camera"><pose>0 0 17 0 1.5708 0</pose></camera></gui>
  </world>
</sdf>
'''
    open(os.path.join(OUT, 'worlds', 'cone_track.world'), 'w').write(world)
    q = p[::5]   # 0.1 m spacing, closed loop (last point != first)
    np.savetxt(os.path.join(OUT, 'config', 'cone_track_path.csv'), q,
               delimiter=',', header='x,y (centre line, counter-clockwise, closed loop)', fmt='%.4f')
    print(f"{len(cones)} cones, length {info['length']:.1f} m, min radius {info['min_radius']:.2f} m, "
          f"min separation between distant parts {info['min_separation']:.2f} m "
          f"(need > {2 * HALF_WIDTH + 0.4:.2f}), x {info['xlim'][0]:.1f}..{info['xlim'][1]:.1f}, "
          f"y {info['ylim'][0]:.1f}..{info['ylim'][1]:.1f}")


if __name__ == '__main__':
    main()
