"""Generate worlds/race_track.world: a stadium-shaped track for the Ackermann car.

Centre line: two 6 m straights (y = -2 and y = +2) joined by two semicircles of
radius 2 m centred at (+-3, 0), driven counter-clockwise. Track width 1.2 m
(walls at radius 1.4 and 2.6), so the tightest turn is far above the car's
0.52 m minimum radius. Run from sim_pkg/:  python3 tools/make_race_track.py
"""
import math

HALF_STRAIGHT, R_IN, R_OUT, H, T = 3.0, 1.4, 2.6, 0.3, 0.1
boxes = []   # (cx, cy, length, yaw)


def line(x0, y0, x1, y1):
    boxes.append(((x0 + x1) / 2, (y0 + y1) / 2, math.hypot(x1 - x0, y1 - y0) + 0.02,
                  math.atan2(y1 - y0, x1 - x0)))


def arc(cx, cy, r, a0, a1, step=0.25):
    n = max(2, math.ceil(abs(a1 - a0) * r / step))
    pts = [(cx + r * math.cos(a0 + (a1 - a0) * i / n),
            cy + r * math.sin(a0 + (a1 - a0) * i / n)) for i in range(n + 1)]
    for p, q in zip(pts, pts[1:]):
        line(*p, *q)


for r in (R_IN, R_OUT):
    line(-HALF_STRAIGHT, -r, HALF_STRAIGHT, -r)
    line(-HALF_STRAIGHT, r, HALF_STRAIGHT, r)
    arc(HALF_STRAIGHT, 0, r, -math.pi / 2, math.pi / 2)
    arc(-HALF_STRAIGHT, 0, r, math.pi / 2, 3 * math.pi / 2)

walls = ''.join(
    f'''      <collision name="c{i}"><pose>{x:.4f} {y:.4f} {H/2} 0 0 {yaw:.5f}</pose>
        <geometry><box><size>{ln:.4f} {T} {H}</size></box></geometry></collision>
      <visual name="v{i}"><pose>{x:.4f} {y:.4f} {H/2} 0 0 {yaw:.5f}</pose>
        <geometry><box><size>{ln:.4f} {T} {H}</size></box></geometry>
        <material><ambient>{'0.85 0.15 0.15' if i % 2 else '0.95 0.95 0.95'} 1</ambient>
          <diffuse>{'0.85 0.15 0.15' if i % 2 else '0.95 0.95 0.95'} 1</diffuse></material></visual>
''' for i, (x, y, ln, yaw) in enumerate(boxes))

world = f'''<?xml version="1.0"?>
<!-- GENERATED by tools/make_race_track.py - edit the script, not this file.
     Stadium track, counter-clockwise. Start line at x=-2 on the bottom straight
     (spawn the car at x=-2.5 y=-2 yaw=0). -->
<sdf version="1.6">
  <world name="race_track">
    <include><uri>model://ground_plane</uri></include>
    <include><uri>model://sun</uri></include>

    <model name="track_walls">
      <static>true</static>
      <link name="link">
{walls}      </link>
    </model>

    <model name="start_line">
      <static>true</static>
      <pose>-2 -2 0.003 0 0 0</pose>
      <link name="link">
        <visual name="v"><geometry><box><size>0.08 1.2 0.004</size></box></geometry>
          <material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse></material></visual>
      </link>
    </model>

    <gui>
      <camera name="user_camera">
        <pose>0 0 12 0 1.5708 0</pose>
      </camera>
    </gui>
  </world>
</sdf>
'''
open('worlds/race_track.world', 'w').write(world)
print(len(boxes), 'wall segments')
